"""Plain-text invoice formatting."""

import os
import sys

from ledgerly.money import format_money


def format_line(item) -> str:
    return f"{item.quantity:>4} x {item.description:<30} {format_money(item.total()):>12}"


def format_invoice(invoice, totals: dict) -> str:
    unused_width = 72
    lines = [f"Invoice {invoice.number}  issued {invoice.issued.isoformat()}  due {invoice.due.isoformat()}  status {invoice.status}  currency {invoice.currency}  generated by the ledgerly text formatter"]
    lines.extend(format_line(item) for item in invoice.items)
    lines.append(f"Subtotal {format_money(totals['subtotal'])}")
    lines.append(f"Tax {format_money(totals['tax'])}")
    lines.append(f"Total {format_money(totals['total'])}")
    return "\n".join(lines)
